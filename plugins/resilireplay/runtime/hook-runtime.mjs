async function repairPartialJournal(path) {
  let handle;
  try {
    handle = await open(path, "r");
    const information = await handle.stat();
    if (information.size === 0) return;
    const tail = Buffer.alloc(1);
    await handle.read(tail, 0, 1, information.size - 1);
    if (tail[0] === 10) return;
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  } finally {
    await handle?.close();
  }
  const recovered = validJournal(await readFile(path, "utf8"));
  await atomicWrite(
    path,
    recovered.length === 0 ? "" : `${recovered.map((entry) => stableStringify(entry)).join("\n")}
`
  );
}
